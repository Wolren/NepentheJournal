def chembl_fetch(chembl_id: str) -> dict[str, Any]:
    """Fetch ChEMBL molecule data and bioactivities."""
    result: dict[str, Any] = {"chemblId": chembl_id}
    if not chembl_id:
        return result

    try:
        # Molecule properties
        r = _client.get(
            f"https://www.ebi.ac.uk/chembl/api/data/molecule/{chembl_id}.json",
        )
        if r.status_code == 200:
            mol = r.json()
            props = mol.get("molecule_properties", {})
            result["mw"] = props.get("mw_freebase")
            result["alogp"] = props.get("alogp")
            result["psa"] = props.get("psa")
            result["ro5Violations"] = props.get("num_ro5_violations")
            # maxPhase can be -1.0 (not applicable) - convert to int
            mp = mol.get("max_phase")
            if mp is not None:
                result["maxPhase"] = int(mp)
            result["prefName"] = mol.get("pref_name")
    except Exception:
        pass

    # Bioactivities: get Ki and IC50 values
    bioact: list[dict[str, Any]] = []
    try:
        for std_type in ["IC50", "Ki", "EC50", "Kd"]:
            r = _client.get(
                "https://www.ebi.ac.uk/chembl/api/data/activity.json",
                params={
                    "molecule_chembl_id": chembl_id,
                    "standard_type": std_type,
                    "limit": 20,
                    "assay_type__in": "B",
                },
            )
            if r.status_code == 200:
                for a in r.json().get("activities", []):
                    bioact.append({
                        "type": std_type,
                        "value": a.get("standard_value"),
                        "units": a.get("standard_units"),
                        "relation": a.get("standard_relation"),
                        "targetId": a.get("target_chembl_id"),
                        "assay": a.get("assay_description", "")[:120] if a.get("assay_description") else "",
                    })
    except Exception:
        pass

    if bioact:
        result["bioactivities"] = bioact
    return result


