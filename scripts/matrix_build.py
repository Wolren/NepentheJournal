def build_chemical_properties(pubchem_data: dict[str, Any] | None) -> dict[str, Any] | None:
    """Build ChemicalProperties object from PubChem data."""
    if not pubchem_data:
        return None
    cp = {
        "cid": pubchem_data.get("CID"),
        "molecularFormula": pubchem_data.get("MolecularFormula"),
        "molecularWeight": pubchem_data.get("MolecularWeight"),
        "smiles": pubchem_data.get("SMILES"),
        "inchiKey": pubchem_data.get("InChIKey"),
        "iupacName": pubchem_data.get("IUPACName"),
        "xlogP": pubchem_data.get("XLogP"),
        "hBondDonorCount": pubchem_data.get("HBondDonorCount"),
        "hBondAcceptorCount": pubchem_data.get("HBondAcceptorCount"),
    }
    # Remove None values
    return {k: v for k, v in cp.items() if v is not None}


def match_name_to_tripsit(
    name: str, aliases: list[str], ts_index: dict[str, str], ts_drugs: dict[str, Any]
) -> tuple[str | None, dict[str, Any] | None]:
    """
    Try to match a substance name or its aliases to a TripSit drug entry.
    Returns (canonical_key, drug_data).
    """
    # Try primary name
    key = name.lower().strip()
    if key in ts_index:
        ts_key = ts_index[key]
        return ts_key, ts_drugs.get(ts_key)

    # Try aliases
    for alias in aliases:
        alias_key = alias.lower().strip()
        if alias_key in ts_index:
            ts_key = ts_index[alias_key]
            return ts_key, ts_drugs.get(ts_key)

    return None, None


def merge_substance(
    smw_sub: dict[str, Any],
    cid: int | None,
    pubchem_props: dict[str, Any] | None,
    tripsit_drug: dict[str, Any] | None,
) -> dict[str, Any]:
    """
    Merge SMW + PubChem + TripSit data into a unified substance record.
    CID becomes the primary ID where available.
    """
    name = smw_sub["name"]
    old_id = smw_sub["id"]

    # New ID: prefer CID
    new_id = f"cid:{cid}" if cid else old_id

    # Merge aliases from all sources
    aliases = list(smw_sub.get("aliases", []))
    ts_aliases = tripsit_drug.get("aliases", []) if tripsit_drug else []
    for a in ts_aliases:
        if a.lower() != name.lower() and a not in aliases:
            aliases.append(a)

    # Merge effects
    effects = list(smw_sub.get("effects", []))
    ts_effects = tripsit_drug.get("formatted_effects", []) if tripsit_drug else []
    for e in ts_effects:
        if e not in effects:
            effects.append(e)

    # Merge categories/classes
    substance_class = list(smw_sub.get("substanceClass", []))
    ts_categories = tripsit_drug.get("categories", []) if tripsit_drug else []
    if ts_categories:
        substance_class.extend([c for c in ts_categories if c not in substance_class])

    # Add Erowid link from TripSit if available
    erowid_url = ""
    if tripsit_drug:
        links = tripsit_drug.get("links", {})
        if isinstance(links, dict):
            erowid_url = links.get("experiences", "")

    # Track sources
    sources = ["psychonautwiki"]
    if cid:
        sources.append("pubchem")
    if tripsit_drug:
        sources.append("tripsit")

    return {
        "id": new_id,
        "oldId": old_id if old_id != new_id else None,
        "cid": cid,
        "docType": "substance",
        "createdAt": smw_sub.get("createdAt") or smw_sub.get("cachedAt"),
        "updatedAt": smw_sub.get("updatedAt") or smw_sub.get("cachedAt"),
        "deviceOrigin": "system",
        "pwikiId": smw_sub.get("pwikiId") or name,
        "name": name,
        "aliases": aliases,
        "summary": smw_sub.get("summary"),
        "substanceClass": substance_class,
        "routesOfAdministration": smw_sub.get("routesOfAdministration", []),
        "dosageBands": smw_sub.get("dosageBands", {}),
        "durationProfile": smw_sub.get("durationProfile", {}),
        "addictionPotential": smw_sub.get("addictionPotential"),
        "toxicity": smw_sub.get("toxicity", []),
        "crossTolerances": smw_sub.get("crossTolerances", []),
        "effects": effects,
        "chemicalProperties": build_chemical_properties(pubchem_props),
        "erowidUrl": erowid_url,
        "sources": sources,
        "cachedAt": smw_sub.get("cachedAt"),
        "sourceVersion": "pwiki-smw-v2",
        "userAnnotations": {},
    }


def merge_interactions(
    smw_interactions: list[dict[str, Any]],
    combos_data: dict[str, Any],
    name_to_cid: dict[str, int | None],
    pwiki_to_new_id: dict[str, str],  # "pwiki:lsd" -> "cid:5761"
    now_ms: int,
) -> list[dict[str, Any]]:
    """
    Merge SMW interactions with TripSit combo data.
    Both are keyed by substance name/category; we map to CIDs.
    """
    seen: set[str] = set()
    merged: list[dict[str, Any]] = []

    def add_interaction(a: str, b: str, risk: str, notes: str | None = None, sources_list: list[str] | None = None):
        # Sort IDs
        ids = sorted([a, b])
        int_id = f"interaction:{ids[0]}:{ids[1]}"
        if int_id in seen:
            return
        seen.add(int_id)
        merged.append({
            "id": int_id,
            "docType": "interaction",
            "createdAt": now_ms,
            "updatedAt": now_ms,
            "deviceOrigin": "system",
            "substanceAId": ids[0],
            "substanceBId": ids[1],
            "riskLevel": risk,
            "description": notes,
            "sources": sources_list or ["psychonautwiki"],
        })

    # Process SMW interactions - map old pwiki: IDs to new cid: IDs
    for interaction in smw_interactions:
        old_a = interaction["substanceAId"]
        old_b = interaction["substanceBId"]
        new_a = pwiki_to_new_id.get(old_a, old_a)
        new_b = pwiki_to_new_id.get(old_b, old_b)
        add_interaction(
            new_a, new_b, interaction["riskLevel"],
        )

    # Process TripSit combos
    name_to_id: dict[str, str] = {}
    for orig_name, cid in name_to_cid.items():
        name_lower = orig_name.lower().strip()
        name_to_id[name_lower] = f"cid:{cid}" if cid else f"pwiki:{orig_name.lower().replace(' ', '_')}"
        # Also add pwiki ID
        name_to_id[orig_name.lower()] = f"cid:{cid}" if cid else f"pwiki:{orig_name.lower().replace(' ', '_')}"

    # Map combo interactions
    for combo_key, combo_targets in combos_data.items():
        sub_a_id = name_to_id.get(combo_key.lower())
        if not sub_a_id:
            continue

        for target_key, combo_info in combo_targets.items():
            sub_b_id = name_to_id.get(target_key.lower())
            if not sub_b_id:
                continue

            ts_risk = combo_info.get("status", "")
            risk = TRIPSIT_RISK_MAP.get(ts_risk, "UNKNOWN")
            note = combo_info.get("note", "")
            sources_list = ["tripsit"]
            if combo_info.get("sources"):
                sources_list.append("peer-reviewed")

            add_interaction(sub_a_id, sub_b_id, risk, note or None, sources_list)

    return merged


