def load_smw_seed(path: str) -> dict[str, Any]:
    """Load the existing SMW-generated seed JSON."""
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def smw_get_all_substance_names() -> list[str]:
    """Fetch fresh substance list from SMW (fallback if no seed)."""
    try:
        r = _client.get(
            f"{SMW_API}?action=ask&query=%5B%5BCategory%3ASubstance%5D%5D%7Climit%3D500&format=json"
        )
        data = r.json()
        names = list(data["query"]["results"].keys())
        return [n for n in names if not n.startswith("Experience:")]
    except Exception:
        return []


