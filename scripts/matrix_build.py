#!/usr/bin/env python3
"""
Multi-source matrix builder for Nepenthe Journal.

Combines data from 5 sources into a unified substance database keyed by
PubChem CID, output as a JournalSnapshot JSON file the app loads at startup.

Sources:
  1. PsychonautWiki SMW   - doses, durations, effects, ROAs, classes, interactions
  2. PubChem              - CID, molecular formula, weight, SMILES, InChIKey, LogP
  3. TripSit              - aliases, categories, Erowid links, interaction chart
  4. Wikidata             - cross-references (ChEMBL ID, DrugBank ID, CAS, etc.)
  5. ChEMBL               - bioactivity data (IC50/Ki/EC50 at molecular targets)

Pipeline stages:
  1. Load SMW seed (generated by scripts/smw_dump.py)
  2. Resolve PubChem CIDs by substance name (cached)
  3. Fetch PubChem molecular properties by CID batch
  4. Fetch TripSit drugs + combos
  5. Cross-reference names: SMW ↔ TripSit
  6. Merge substances (CID-based IDs, filter categories, keep botanicals)
  7. Build interactions (SMW + TripSit combos)
  8. Fetch Wikidata cross-references (cached)
  9. Fetch ChEMBL bioactivities (cached)
  10. Write JournalSnapshot JSON

Usage:
    # Full rebuild (downloads everything)
    python scripts/matrix_build.py --input seed.json --output final.json --verbose

    # Incremental update (uses cached API results)
    python scripts/matrix_build.py --input seed.json --output final.json --verbose

    # Full refresh (delete caches, re-download)
    python scripts/matrix_build.py --input seed.json --output final.json --refresh --verbose

Cache files (*_cache.json) persist between runs so only new/missing data
is fetched. Delete them to force a full re-download.

Requires: httpx (pip install httpx)
"""

