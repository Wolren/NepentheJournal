WIKIDATA_PROPS = {
    "P662": "pubchemCid", "P592": "chemblId", "P715": "drugbankId",
    "P595": "iupharId", "P1117": "cas", "P661": "chemspiderId",
    "P652": "unii", "P267": "atcCode", "P2084": "keggId",
    "P2057": "hmdbId", "P683": "chebiId", "P232": "ecNumber",
    "P665": "rxnorm", "P3117": "dsstoxCid",
}
WIKIDATA_STANDARD_PROPS = ["chemblId", "drugbankId", "iupharId", "chemspiderId",
                           "unii", "chebiId", "atcCode"]


def wikidata_batch_fetch(cids: list[int], batch_size: int = 30) -> dict[int, dict[str, Any]]:
    """
    Batch Wikidata lookup using per-CID API calls with concurrent workers.
    Returns {cid: {qid, chemblId, drugbankId, ...}}
    """
    import concurrent.futures

    def lookup_single(cid: int) -> tuple[int, dict[str, Any]]:
        try:
            # Step 1: Find QID via haswbstatement search
            r = _client.get(
                "https://www.wikidata.org/w/api.php",
                params={"action": "query", "list": "search",
                        "srsearch": f"haswbstatement:P662={cid}",
                        "srlimit": 1, "format": "json"},
                timeout=15,
            )
            if r.status_code == 429:
                time.sleep(3)
                r = _client.get(
                    "https://www.wikidata.org/w/api.php",
                    params={"action": "query", "list": "search",
                            "srsearch": f"haswbstatement:P662={cid}",
                            "srlimit": 1, "format": "json"},
                    timeout=15,
                )
            if r.status_code != 200:
                return cid, {}
            results = r.json().get("query", {}).get("search", [])
            if not results:
                return cid, {}
            qid = results[0]["title"]

            # Step 2: Fetch full entity for cross-references
            r2 = _client.get(
                f"https://www.wikidata.org/wiki/Special:EntityData/{qid}.json",
                timeout=15,
            )
            if r2.status_code != 200:
                return cid, {"qid": qid}

            claims = r2.json()["entities"][qid].get("claims", {})
            entry: dict[str, Any] = {"qid": qid}

            wd_pid_map = {
                "P592": "chemblId", "P715": "drugbankId", "P595": "iupharId",
                "P661": "chemspiderId", "P652": "unii", "P683": "chebiId",
                "P267": "atcCode", "P1117": "cas", "P2084": "keggId",
                "P2057": "hmdbId", "P665": "rxnorm", "P3117": "dsstoxCid",
            }
            for pid, key in wd_pid_map.items():
                if pid in claims:
                    snak = claims[pid][0]["mainsnak"]
                    if snak["snaktype"] == "value":
                        dv = snak["datavalue"]["value"]
                        if isinstance(dv, dict):
                            dv = dv.get("id", str(dv))
                        entry[key] = dv
            return cid, entry
        except Exception:
            return cid, {}

    result: dict[int, dict[str, Any]] = {}

    # Use ThreadPoolExecutor for concurrent lookups
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        fut_map = {pool.submit(lookup_single, cid): cid for cid in cids}
        done = 0
        for future in concurrent.futures.as_completed(fut_map):
            cid, entry = future.result()
            if entry:
                result[cid] = entry
            done += 1
            # Rate limit: sleep after every 3 completes
            if done % 3 == 0 and done < len(cids):
                time.sleep(1.0)
    return result


def wikidata_fetch_entity(qid: str) -> dict[str, Any]:
    """Fetch Wikidata entity JSON and extract cross-references."""
    result: dict[str, Any] = {"qid": qid}
    try:
        r = _client.get(
            f"https://www.wikidata.org/wiki/Special:EntityData/{qid}.json",
        )
        if r.status_code == 200:
            claims = r.json()["entities"][qid].get("claims", {})
            for pid, label in WIKIDATA_PROPS.items():
                if pid in claims:
                    snak = claims[pid][0]["mainsnak"]
                    if snak["snaktype"] == "value":
                        dv = snak["datavalue"]["value"]
                        if isinstance(dv, dict):
                            dv = dv.get("id", str(dv))
                        result[label] = dv
    except Exception:
        pass
    return result


