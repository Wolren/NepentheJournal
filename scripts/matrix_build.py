def pubchem_cid(name: str) -> int | None:
    """Resolve a substance name to a PubChem CID."""
    # Check manual overrides first
    if name in MANUAL_CID_OVERRIDES:
        return MANUAL_CID_OVERRIDES[name]

    # Check name override
    query = PUBCHEM_NAME_OVERRIDES.get(name, name)

    try:
        url = f"{PUBCHEM_BASE}/compound/name/{urllib.parse.quote(query)}/cids/JSON"
        r = _client.get(url)
        if r.status_code == 200:
            data = r.json()
            cids = data.get("IdentifierList", {}).get("CID", [])
            return cids[0] if cids else None
        return None
    except Exception:
        return None


def pubchem_batch_properties(cids: list[int]) -> dict[int, dict[str, Any]]:
    """Fetch molecular properties for a batch of CIDs via POST."""
    results: dict[int, dict[str, Any]] = {}
    if not cids:
        return results

    # Split into batches of 50 (PubChem max)
    batch_size = 50
    for i in range(0, len(cids), batch_size):
        batch = cids[i:i + batch_size]
        try:
            url = f"{PUBCHEM_BASE}/compound/cid/{','.join(str(c) for c in batch)}/property/{PUBCHEM_PROPS}/JSON"
            r = _client.get(url)
            if r.status_code == 200:
                data = r.json()
                for prop in data.get("PropertyTable", {}).get("Properties", []):
                    cid = prop.get("CID")
                    if cid:
                        results[cid] = prop
        except Exception:
            pass
        time.sleep(0.1)

    return results


def pubchem_property(cid: int) -> dict[str, Any] | None:
    """Fetch molecular properties for a single CID."""
    try:
        url = f"{PUBCHEM_BASE}/compound/cid/{cid}/property/{PUBCHEM_PROPS}/JSON"
        r = _client.get(url)
        if r.status_code == 200:
            data = r.json()
            props = data.get("PropertyTable", {}).get("Properties", [])
            if props:
                return props[0]
        return None
    except Exception:
        return None


