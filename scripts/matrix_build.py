def main():
    parser = argparse.ArgumentParser(description="Build unified substance matrix")
    parser.add_argument("--input", "-i", default="", help="Input SMW seed JSON")
    parser.add_argument("--output", "-o", default="unified_seed.json", help="Output path")
    parser.add_argument("--refresh", "-r", action="store_true", help="Delete caches and re-download all data")
    parser.add_argument("--verbose", "-v", action="store_true")
    args = parser.parse_args()

    # Refresh: delete all cache files
    if args.refresh:
        for fname in ["pubchem_cid_cache.json", "wikidata_cache.json", "chembl_cache.json"]:
            if os.path.exists(fname):
                os.remove(fname)
                if args.verbose:
                    print(f"[*] Deleted cache: {fname}", file=sys.stderr)

    now_ms = int(datetime.now(timezone.utc).timestamp() * 1000)

    # --- Stage 0: Load or fetch SMW data ---
    if args.input:
        if args.verbose:
            print(f"[*] Loading SMW seed from {args.input}", file=sys.stderr)
        smw_data = load_smw_seed(args.input)
        substances_raw = smw_data.get("substances", [])
        interactions_raw = smw_data.get("interactions", [])
    else:
        if args.verbose:
            print("[*] Fetching fresh SMW data from wiki...", file=sys.stderr)
        # Run the SMW dump inline (simplified: just names + smwbrowse)
        from smw_dump import get_all_substance_names, get_substance_properties, smw_to_substance, smw_to_interactions, get_summaries
        names = get_all_substance_names()
        names = [n for n in names if not n.startswith("Experience:")]
        summaries = get_summaries(names)
        substances_raw = []
        interactions_raw = []
        all_ints: dict[str, dict] = {}
        for i, n in enumerate(names, 1):
            props = get_substance_properties(n)
            sub = smw_to_substance(n, props, summaries.get(n), now_ms)
            substances_raw.append(sub)
            ints = smw_to_interactions(n, props, now_ms)
            for intv in ints:
                all_ints[intv["id"]] = intv
            if args.verbose and i % 50 == 0:
                print(f"  [{i}/{len(names)}] SMW fetch...", file=sys.stderr)
            time.sleep(0.15)
        interactions_raw = list(all_ints.values())

    if args.verbose:
        print(f"[+] Loaded {len(substances_raw)} substances, {len(interactions_raw)} interactions from SMW", file=sys.stderr)

    # --- Stage 1: Resolve PubChem CIDs ---
    if args.verbose:
        print("[*] Resolving PubChem CIDs...", file=sys.stderr)

    # Try loading cached CID map
    pubchem_cid_cache = "pubchem_cid_cache.json"
    name_to_cid: dict[str, int | None] = {}
    cid_to_name: dict[int, str] = {}
    if os.path.exists(pubchem_cid_cache):
        try:
            with open(pubchem_cid_cache) as f:
                raw = json.load(f)
                name_to_cid = {k: (int(v) if v else None) for k, v in raw.items()}
            if args.verbose:
                cached = sum(1 for v in name_to_cid.values() if v is not None)
                print(f"[*] Loaded {cached}/{len(name_to_cid)} cached CIDs", file=sys.stderr)
        except Exception:
            name_to_cid = {}

    resolved_count = 0
    missing_names = [s["name"] for s in substances_raw if s["name"] not in name_to_cid]
    for name in missing_names:
        cid = None
        if name not in NO_CID_NAMES:
            cid = pubchem_cid(name)
            if cid is None:
                sub = next((s for s in substances_raw if s["name"] == name), None)
                if sub:
                    for alias in sub.get("aliases", []):
                        cid = pubchem_cid(alias)
                        if cid:
                            break
        name_to_cid[name] = cid
        if cid:
            cid_to_name[cid] = name
            resolved_count += 1
        time.sleep(PUBCHEM_DELAY)

    # Save cache
    try:
        with open(pubchem_cid_cache, "w") as f:
            json.dump({k: v for k, v in name_to_cid.items()}, f)
    except Exception:
        pass

    if args.verbose:
        print(f"[+] Resolved {resolved_count}/{len(substances_raw)} CIDs", file=sys.stderr)

    # --- Stage 2: Fetch PubChem properties (batch) ---
    all_cids = [cid for cid in name_to_cid.values() if cid is not None]
    if args.verbose:
        print(f"[*] Fetching PubChem properties for {len(all_cids)} CIDs...", file=sys.stderr)

    cid_props = pubchem_batch_properties(all_cids)
    if args.verbose:
        print(f"[+] Got properties for {len(cid_props)}/{len(all_cids)} CIDs", file=sys.stderr)

    # --- Stage 3: Fetch TripSit data ---
    if args.verbose:
        print("[*] Fetching TripSit drugs...", file=sys.stderr)
    ts_drugs = tripsit_get_all_drugs()
    ts_index = tripsit_name_index(ts_drugs)
    if args.verbose:
        print(f"[+] TripSit has {len(ts_drugs)} drugs", file=sys.stderr)

    if args.verbose:
        print("[*] Fetching TripSit combos...", file=sys.stderr)
    ts_combos = tripsit_get_combos()
    if args.verbose:
        print(f"[+] TripSit combos: {len(ts_combos)} categories", file=sys.stderr)

    # --- Stage 4: Merge substances ---
    if args.verbose:
        print("[*] Merging data sources...", file=sys.stderr)

    merged_substances = []
    ts_match_count = 0

    for sub in substances_raw:
        name = sub["name"]
        cid = name_to_cid.get(name)
        pubchem_data = cid_props.get(cid) if cid else None
        ts_key, ts_drug = match_name_to_tripsit(name, sub.get("aliases", []), ts_index, ts_drugs)
        if ts_drug:
            ts_match_count += 1
        merged = merge_substance(sub, cid, pubchem_data, ts_drug)
        merged_substances.append(merged)

    if args.verbose:
        cid_count = sum(1 for s in merged_substances if s["cid"])
        pchem_count = sum(1 for s in merged_substances if s.get("chemicalProperties"))
        print(f"[+] Merged: {len(merged_substances)} substances", file=sys.stderr)
        print(f"    CID: {cid_count} | PubChem props: {pchem_count} | TripSit match: {ts_match_count}", file=sys.stderr)

    # --- Stage 4b: Filter out conceptual categories (keep real compounds + botanicals) ---
    BOTANICALS = {
        "Salvia divinorum", "Kratom", "Amanita muscaria", "Psilocybe cubensis",
        "Banisteriopsis caapi", "Peganum harmala", "Atropa belladonna",
        "Mandragora", "Tabernanthe iboga", "Datura", "Coca",
        "Morning glory", "Changa", "Ayahuasca", "Anadenanthera peregrina",
        "Blue Lotus", "Psilocybin mushrooms", "Cannabis",
        "Piper nigrum (botany)", "Cocoa",
    }

    def is_real_substance(sub: dict) -> bool:
        if sub.get("cid"):
            return True
        db = sub.get("dosageBands", {})
        dp = sub.get("durationProfile", {})
        has_dose = bool(db and any(v for v in db.values()))
        has_dur = bool(dp and any(v for v in dp.values()))
        if has_dose or has_dur:
            return True
        if sub.get("name") in BOTANICALS:
            return True
        return False

    before = len(merged_substances)
    merged_substances = [s for s in merged_substances if is_real_substance(s)]
    excluded_names = set()
    for s in merged_substances:
        excluded_names.add(s["name"].lower())
    excluded_count = before - len(merged_substances)
    if args.verbose:
        print(f"[+] Filtered: removed {excluded_count} category pages, kept {len(merged_substances)}", file=sys.stderr)

    # --- Stage 5: Merge interactions ---
    # Build old ID -> new ID mapping from merged substances
    pwiki_to_new_id: dict[str, str] = {}
    for sub in merged_substances:
        old_id = sub.get("oldId")
        if old_id and old_id != sub["id"]:
            pwiki_to_new_id[old_id] = sub["id"]

    merged_interactions = merge_interactions(
        interactions_raw, ts_combos, name_to_cid,
        pwiki_to_new_id,
        now_ms,
    )

    if args.verbose:
        print(f"[+] Interactions: {len(merged_interactions)} (SMW: {len(interactions_raw)} + TripSit combos)", file=sys.stderr)

    # --- Stage 6: Wikidata cross-references + ChEMBL bioactivity ---
    cids_with_chembl = [sub["cid"] for sub in merged_substances if sub.get("cid")]
    wd_map: dict[int, dict[str, Any]] = {}

    # Try loading cached Wikidata results
    wikidata_cache_file = "wikidata_cache.json"
    if os.path.exists(wikidata_cache_file):
        try:
            with open(wikidata_cache_file) as f:
                wd_map = {int(k): v for k, v in json.load(f).items()}
            if args.verbose:
                print(f"[*] Loaded {len(wd_map)} cached Wikidata entries", file=sys.stderr)
        except Exception:
            wd_map = {}

    # Fetch missing entries
    missing = [c for c in cids_with_chembl if c not in wd_map]
    if missing:
        if args.verbose:
            print(f"[*] Wikidata lookup for {len(missing)} uncached CIDs...", file=sys.stderr)
        new_wd = wikidata_batch_fetch(missing)
        wd_map.update(new_wd)
        # Save cache
        try:
            with open(wikidata_cache_file, "w") as f:
                json.dump({str(k): v for k, v in wd_map.items()}, f)
        except Exception:
            pass

    if args.verbose:
        print(f"[+] Wikidata: {len(wd_map)}/{len(cids_with_chembl)}", file=sys.stderr)

    # Fetch ChEMBL for those with ChEMBL IDs
    chembl_cache_file = "chembl_cache.json"
    chembl_cache: dict[str, dict[str, Any]] = {}
    if os.path.exists(chembl_cache_file):
        try:
            with open(chembl_cache_file) as f:
                chembl_cache = json.load(f)
            if args.verbose:
                print(f"[*] Loaded {len(chembl_cache)} cached ChEMBL entries", file=sys.stderr)
        except Exception:
            chembl_cache = {}

    chembl_missing = []
    for cid, wd in wd_map.items():
        chembl_id = wd.get("chemblId")
        if chembl_id and chembl_id not in chembl_cache:
            chembl_missing.append((cid, chembl_id))

    chembl_found = 0
    if chembl_missing:
        if args.verbose:
            print(f"[*] Fetching ChEMBL for {len(chembl_missing)} compounds...", file=sys.stderr)
        for cid, chembl_id in chembl_missing:
            ch = chembl_fetch(chembl_id)
            if ch.get("bioactivities"):
                chembl_cache[chembl_id] = ch
                chembl_found += 1
            if len(chembl_cache) % 10 == 0 and args.verbose:
                print(f"  [ChEMBL] {len(chembl_cache)} fetched so far", file=sys.stderr)
        # Save cache
        try:
            with open(chembl_cache_file, "w") as f:
                json.dump(chembl_cache, f)
        except Exception:
            pass
    else:
        if args.verbose:
            print(f"[*] ChEMBL: all {len(chembl_cache)} cached", file=sys.stderr)

    if args.verbose:
        chembl_with_bio = sum(1 for v in chembl_cache.values() if v.get("bioactivities"))
        print(f"[+] ChEMBL bioactivity: {chembl_with_bio} compounds", file=sys.stderr)

    # Merge into substances
    for sub in merged_substances:
        cid = sub.get("cid")
        if cid and cid in wd_map:
            wd = wd_map[cid]
            for key in WIKIDATA_STANDARD_PROPS:
                if key in wd:
                    sub[key] = wd[key]
            # Add ChEMBL data
            chembl_id = wd.get("chemblId")
            if chembl_id and chembl_id in chembl_cache:
                ch = chembl_cache[chembl_id]
                sub["chemblData"] = {
                    "prefName": ch.get("prefName"),
                    "mw": ch.get("mw"),
                    "alogp": ch.get("alogp"),
                    "psa": ch.get("psa"),
                    "ro5Violations": ch.get("ro5Violations"),
                    "maxPhase": ch.get("maxPhase"),
                    "bioactivities": ch.get("bioactivities", []),
                }

    if args.verbose:
        ref_count = sum(1 for s in merged_substances if s.get("chemblId"))
        bc_count = sum(1 for s in merged_substances if s.get("chemblData"))
        print(f"[+] Wikidata cross-refs: {ref_count} | ChEMBL bioactivity: {bc_count}", file=sys.stderr)

    # --- Stage 7: Write output ---
    snapshot = {
        "version": 3,
        "savedAt": now_ms,
        "sessions": [],
        "substances": merged_substances,
        "doses": [],
        "notes": [],
        "timelineEvents": [],
        "interactions": merged_interactions,
        "customUnits": [],
        "useShulginRating": False,
    }

    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(snapshot, f, indent=2, ensure_ascii=False)

    if args.verbose:
        size = len(json.dumps(snapshot, indent=2, ensure_ascii=False))
        print(f"[+] Wrote {args.output} ({size / 1024:.1f} KB)", file=sys.stderr)


if __name__ == "__main__":
    main()
